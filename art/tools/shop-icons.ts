function frame(rows: readonly string[], colour: string): Frame {
  return rows.map((row) =>
    [...row].map((cell) => (cell === "#" ? colour : cell === "o" ? INK : null)),
  );
}

for (const [key, { disabled, rows }] of Object.entries(ICONS)) {
  const tags: Tag[] = disabled
    ? [
        ["normal", [frame(rows, CREAM)], 100],
        ["disabled", [frame(rows, DISABLED)], 100],
      ]
    : [["rest", [frame(rows, CREAM)], 100]];
  await writeSprites({ data: `${output}${key}.json`, sheet: `${output}${key}.png` }, { key }, tags);
}
